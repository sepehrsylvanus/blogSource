async function main() {
  const { prisma } = await import("../src/lib/prisma");
  try {
    const admin = await prisma.user.findUnique({ where: { email } });
    if (!admin || admin.role !== "admin")
      throw new Error(
        "Create an admin with db:admin first; pass that email to db:demo.",
      );
    for (const story of stories) {
      const category = await prisma.category.findUniqueOrThrow({
        where: { slug: story.category },
      });
      const tagRows = await prisma.tag.findMany({
        where: { slug: { in: [...story.tags] } },
        select: { id: true },
      });
      await prisma.post.upsert({
        where: { slug: story.slug },
        update: {},
        create: {
          authorId: admin.id,
          categoryId: category.id,
          title: story.title,
          slug: story.slug,
          excerpt: story.excerpt,
          body: story.body,
          status: "published",
          publishedAt: new Date(Date.now() - story.daysAgo * 86_400_000),
          postTags: {
            create: tagRows.map(({ id }) => ({ tag: { connect: { id } } })),
          },
        },
      });
    }
    await prisma.post.upsert({
      where: { slug: "private-draft-example" },
      update: {},
      create: {
        authorId: admin.id,
        title: "نمونهٔ پیش‌نویس خصوصی؛ هنوز منتشر نشده",
        slug: "private-draft-example",
        excerpt:
          "این پیش‌نویس فقط در میز نویسنده دیده می‌شود و نباید در صفحات عمومی ظاهر شود.",
        body: "# پیش‌نویس خصوصی\n\nاین متن برای آزمایش رفتار پیش‌نویس ساخته شده است. پس از ورود مدیر می‌توانی پیش‌نمایش را ببینی.",
        status: "draft",
        publishedAt: null,
      },
    });
    console.log(
      "Six published demo stories and one private draft are ready. Idempotent; development only.",
    );
  } finally {
    await prisma.$disconnect();
  }
}
main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
